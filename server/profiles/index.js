// Profile loader. A profile is the whole strategy of a deployment: who you
// sell to, what counts as a signal, which way each signal points, how fast it
// goes stale, and which accounts you already hold. The pipeline is generic.
//
// PROFILE=<key> in .env sets the default; the dashboard and /api/run can
// select either profile per run, and each one keeps its own data directory so
// two markets never merge into one register.
//
// Two profiles ship, deliberately chosen to be opposites rather than variants:
//
//   nvidia       a vendor selling into the AI infrastructure market. An
//                appointment is a LEAD. Commercial value is DEAL SCALE,
//                because revenue is concentrated in one line and breadth
//                measures nothing.
//   exec-search  an ESG executive search firm. The same appointment is a DEAD
//                LEAD. Commercial value is MULTI-SERVICE breadth, the engine
//                default, because breadth genuinely varies signal to signal.
//
// That pair is the proof of concept: identical code, identical agents,
// opposite readings of the identical event. A third market means writing a
// third file — see profiles/README.md for the questions it must answer.
import nvidia from './nvidia.js';
import execSearch from './exec-search.js';
// Generated by tools/build-profile.mjs from the company's own website, a
// research brief and six past wins — in about a minute, for no search credits.
// Proof that a third market is a file, not an engine change.
import consultancy from './consultancy.js';
// Three more sectors, ported from the operator's own tested prompt packs. Each
// is a genuinely different business — hospitality sold city by city, a think
// tank funded by foundations, an agency paid when a claim is challenged — and
// none of them needed a line of engine code.
import servicedApartments from './serviced-apartments.js';
import thinkTank from './think-tank.js';
import sustainabilityComms from './sustainability-comms.js';

const PROFILES = {
  nvidia,
  'exec-search': execSearch,
  consultancy,
  'serviced-apartments': servicedApartments,
  'think-tank': thinkTank,
  'sustainability-comms': sustainabilityComms,
};

export const DEFAULT_PROFILE = process.env.PROFILE || 'nvidia';

// Profiles the system generated for itself, loaded from data/profiles/*.json.
//
// Kept in a separate map from the shipped ones so the two can never be
// confused: a generated profile is a draft until a human has read its polarity
// block, and the dashboard says so. Registered at boot and whenever one is
// built, so a judge can create a business and run it without a restart.
const GENERATED = new Map();

export function registerGenerated(profile) {
  if (!profile?.key) throw new Error('a generated profile needs a key');
  GENERATED.set(profile.key, profile);
  return profile;
}

export const unregisterGenerated = (key) => GENERATED.delete(key);

/**
 * Load every profile the system has generated for itself.
 *
 * Called by the server at boot AND by the pipeline before a run, so a profile
 * built in the dashboard can be run from the command line and vice versa. The
 * import is dynamic to keep this module loadable by tests that have no data
 * directory.
 */
export async function loadGeneratedProfiles() {
  const { listGenerated, readGenerated } = await import('../lib/profile-write.js');
  const loaded = [];
  for (const key of await listGenerated()) {
    const p = await readGenerated(key);
    if (p?.key) { GENERATED.set(p.key, p); loaded.push(p.key); }
  }
  return loaded;
}

export const profileKeys = () => [...Object.keys(PROFILES), ...GENERATED.keys()];

export function loadProfile(key = DEFAULT_PROFILE) {
  const profile = PROFILES[key] ?? GENERATED.get(key);
  if (!profile) {
    throw new Error(`Unknown profile "${key}" — available: ${profileKeys().join(', ')}`);
  }
  return profile;
}

export const listProfiles = () =>
  [...Object.values(PROFILES), ...GENERATED.values()].map(({ key, name, description, market, roster = [], collectors = [], practiceAreas = [], scoring = {}, generated = false, polarity = [], polarityQuestions = [] }) =>
    ({
      key,
      name,
      description,
      market: market ?? null,
      accounts: roster.length,
      collectors: collectors.length,
      practice_areas: practiceAreas.length,
      // Named so the dashboard can show WHAT each configuration measures,
      // which is the difference a reader should notice between the two.
      value_factor: scoring.valueFactor?.name ?? 'Multi-Service Potential',
      is_default: key === DEFAULT_PROFILE,
      generated,
      // A generated profile whose polarity is still empty will run and will
      // score badly, and the dashboard needs to be able to say so.
      needs_polarity: generated && polarity.length === 0,
      open_questions: polarityQuestions.length,
    }));
